def _build_graph():
    g = {}
    for a, b, h, line in GRAPH_EDGES:
        g.setdefault(a, []).append((b, h, line))
        g.setdefault(b, []).append((a, h, line))
    return g


GRAPH = _build_graph()


def _normalize(name: str) -> str:
    """去掉 市/县/站/高铁站 等后缀，便于匹配。"""
    return re.sub(r"(市|县|高铁站|火车站|站)$", "", name.strip())


def _resolve_city(name: str):
    """把任意输入解析为 (城市标准名, [车站列表])；海外城市返回 ('海外', 国家)。"""
    n = _normalize(name)
    if n in OVERSEAS_CITIES:
        return ("海外", OVERSEAS_CITIES[n])
    # 精确匹配
    if n in CITY_STATIONS:
        return (n, CITY_STATIONS[n])
    # 包含匹配（如 "四川省内江市威远县" -> 威远）
    for city, sts in CITY_STATIONS.items():
        if city in n or n in city:
            return (city, sts)
    return (None, [])


def _dijkstra(starts, goals, max_transfer=2):
    """从 starts(集合) 到 goals(集合) 的最短路径（按历时，优先少换乘/直达）。

    代价 = 真实历时 + 每段固定的换乘隐性成本(TRANSFER_PENALTY)，
    使「直达 / 少换乘」优先于「略快但需多次中转」的方案
    （例如成都东→深圳北走直达 7.8h，优于经广州南换乘 7.5h 但多一次中转）。

    最多允许 max_transfer 次换乘（即最多 max_transfer+1 段）。
    返回 (path, total_hours)，path 为 [(a, b, line), ...]；无解返回 None。
    """
    import heapq
    TRANSFER_PENALTY = 0.6  # 每段换乘的隐性成本（小时），用于优先少换乘/直达
    dist = {s: 0.0 for s in starts}
    prev = {s: (None, 0.0, "") for s in starts}
    pq = [(0.0, s) for s in starts]
    visited = set()
    while pq:
        d, node = heapq.heappop(pq)
        if node in visited:
            continue
        visited.add(node)
        if node in goals:
            path = []
            cur = node
            total = 0.0
            while prev[cur][0] is not None:
                p, h, line = prev[cur]
                path.append((p, cur, line))
                total += h
                cur = p
            path.reverse()
            return path, total
        if node not in GRAPH:
            continue
        # 当前 node 已走过的段数（= 已换乘次数）
        segs = len(path_nodes(prev, node)) - 1
        for nb, h, line in GRAPH[node]:
            # 加上这一段后的换乘次数超过上限则剪枝
            if segs + 1 - 1 > max_transfer:
                continue
            nd = d + h + TRANSFER_PENALTY
            if nb not in dist or nd < dist[nb]:
                dist[nb] = nd
                prev[nb] = (node, h, line)
                heapq.heappush(pq, (nd, nb))
    return None


def path_nodes(prev, node):
    """回溯从起点到 node 的节点序列。"""
    nodes = [node]
    cur = node
    while prev.get(cur) and prev[cur][0] is not None:
        cur = prev[cur][0]
        nodes.append(cur)
    nodes.reverse()
    return nodes


def _stations_text(city, stations):
    note = ""
    for st in stations:
        if st in STATION_NOTES:
            note = f"（{STATION_NOTES[st]}）"
            break
    return f"{city}：{'/'.join(stations)}{note}"


@mcp.tool()
async def query_train(from_station: str, to_station: str, date: str = None) -> str:
    """查询两城市之间的高铁/火车出行方案（线路参考）。

    :param from_station: 出发城市，如 "威远" "东莞" "成都" "北京"
    :param to_station: 到达城市，如 "深圳" "广州" "东京"
    :param date: 可选，出行日期（仅作提示；线路方案不依赖具体日期）
    :return: 高铁线路方案文本，含换乘站点、大致历时、所属干线；
             并注明「实时车次/票价/余票请以 12306 为准」。
             跨国城市会说明高铁不适用、需乘飞机。
    """
    f_city, f_sts = _resolve_city(from_station)
    t_city, t_sts = _resolve_city(to_station)

    # 跨国判断
    if f_city == "海外":
        return (f"❓「{from_station}」位于{f_sts}（海外），高铁不适用，需乘飞机前往。"
                f"当前 Demo 尚未接入航班查询工具，建议自行查询航班。")
    if t_city == "海外":
        return (f"✈️ 「{to_station}」位于{t_sts}（海外），高铁/火车无法直达，需要乘飞机。"
                f"当前 Demo 尚未接入航班查询工具，建议查询机票。")

    if f_city is None:
        return f"❓ 未收录出发城市：{from_station}，请尝试更常见的城市名（如'成都''深圳'）。"
    if t_city is None:
        return f"❓ 未收录到达城市：{to_station}，请尝试更常见的城市名。"

    starts = set(f_sts)
    goals = set(t_sts)
    res = _dijkstra(starts, goals, max_transfer=2)
    if not res:
        return (f"❓ 在高铁网络中没有找到 {from_station} → {to_station} 的线路方案"
                f"（可能需超过 2 次中转，或该城市暂未收录）。"
                f"建议以 12306 官方查询结果为准。")

    path, total = res
    lines = []
    lines.append(f"🚄 {from_station} → {to_station} 高铁方案（线路参考，实时车次/票价/余票以 12306 为准）：")
    seg_idx = 1
    for a, b, line in path:
        # 这一段的大致历时 = 图中边权
        h = None
        for nb, hh, ln in GRAPH[a]:
            if nb == b:
                h = hh
                break
        lines.append(f"  {seg_idx}. {a} → {b}（约 {h:.1f} 小时，{line}）")
        seg_idx += 1
    transfers = len(path) - 1
    if transfers == 0:
        lines.append(f"✅ 全程约 {total:.1f} 小时，有直达车次，无需换乘。")
    else:
        lines.append(f"全程约 {total:.1f} 小时，需在途换乘 {transfers} 次。")
    # 车站备注：仅列出本方案实际经过的车站（如威远已通高铁）
    used_stations = set()
    for a, b, _ in path:
        used_stations.add(a)
        used_stations.add(b)
    note_parts = []
    for st in used_stations:
        if st in STATION_NOTES:
            note_parts.append(STATION_NOTES[st])
    if note_parts:
        lines.append("ℹ️ " + " ".join(dict.fromkeys(note_parts)))
    # 决策 2：规划参考 + 跳转 12306 购买（自身不接实时票 / 登录 / 下单）
    buy_hint = f"{from_station} → {to_station}"
    if date:
        buy_hint += f"（{date}）"
    lines.append(
        f"🔗 以上为线路参考，购票请前往 12306：https://www.12306.cn "
        f"（搜索「{buy_hint}」获取实时车次 / 票价 / 余票）"
    )
    return "\n".join(lines)


